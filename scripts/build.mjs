#!/usr/bin/env node
// Build Baseline: tokens/*.tokens.json (exported from Figma) -> dist/
//
//   node scripts/build.mjs                       # default theme (tokens/theme.tokens.json)
//   node scripts/build.mjs --theme themes/x.tokens.json   # build with a different theme file
//
// Outputs
//   dist/tokens.css      CSS custom properties. Semantic colors reference primitives via var(),
//                        so a theme can also be swapped at runtime by overriding primitives.
//   dist/typography.css  .bl-text-* classes generated from Figma text styles
//   dist/tokens.json     Flat, fully-resolved values (light + dark) for JS / tooling
//   dist/baseline.css    tokens + typography + css/base.css + css/components/*.css in one file
import fs from 'node:fs';
import path from 'node:path';
import { ROOT, loadTokens, validate, resolve, isRef, refId } from './lib/tokens.mjs';

const args = process.argv.slice(2);
const themeFile = args.includes('--theme') ? args[args.indexOf('--theme') + 1] : null;
const REM_BASE = 16;

const flat = loadTokens({ themeFile });
validate(flat);

const ORDER = ['scale', 'theme', 'dimension', 'typography', 'motion', 'color'];
const byFile = (name) => [...flat.values()].filter((t) => t.file === `${name}.tokens.json`);
const cssName = (id) => flat.get(id).css;

const FONT_FALLBACK = 'ui-sans-serif, system-ui, -apple-system, "Segoe UI", sans-serif';

function literal(t, v) {
  switch (t.type) {
    case 'dimension': {
      const n = parseFloat(v);
      // Strokes stay in px (hairlines shouldn't scale with user font size); everything else -> rem.
      if (/^--stroke-/.test(t.css) || n === 0) return n === 0 ? '0' : `${n}px`;
      return `${+(n / REM_BASE).toFixed(4)}rem`;
    }
    case 'fontFamily':
      return `"${v}", ${FONT_FALLBACK}`;
    case 'cubicBezier':
      return Array.isArray(v) ? `cubic-bezier(${v.join(', ')})` : v;
    case 'color':
    case 'duration':
    case 'fontWeight':
    default:
      return String(v);
  }
}
const value = (t, v) => (isRef(v) ? `var(${cssName(refId(v))})` : literal(t, v));

const banner = `/* Baseline design tokens — GENERATED by scripts/build.mjs from tokens/*.tokens.json.
 * Do not edit by hand: change values in Figma, export with the Baseline Tokens plugin, rebuild.
 * AI tools: reference these custom properties; never substitute literal values.
 * Theme: ${themeFile ? path.relative(ROOT, path.resolve(themeFile)) : 'tokens/theme.tokens.json'}
 */\n`;

let css = banner + ':root {\n';
for (const file of ORDER.filter((f) => f !== 'color')) {
  const toks = byFile(file);
  if (!toks.length) continue;
  css += `\n  /* ${file} */\n`;
  for (const t of toks) {
    const px = t.type === 'dimension' ? resolve(flat, t.value) : null;
    css += `  ${t.css}: ${value(t, t.value)};${px && isRef(t.value) ? ` /* ${px} */` : ''}\n`;
  }
}
const color = byFile('color');
// Shadows (from Figma effect styles) reference mode-dependent colors, so they're redeclared in
// every mode block — that way data-theme works on any subtree, not just <html>.
const shadows = [...flat.values()].filter((t) => t.type === 'shadow');
const shadowLines = (indent) =>
  shadows.map((t) => {
    const layers = t.value.map((l) => `${l.inset ? 'inset ' : ''}${l.offsetX} ${l.offsetY} ${l.blur} ${l.spread} ${isRef(l.color) ? `var(${cssName(refId(l.color))})` : l.color}`);
    return `${indent}--${t.id.replace(/\./g, '-')}: ${layers.join(', ')};`;
  }).join('\n');
const modeBlock = (mode, indent) =>
  color.map((t) => `${indent}${t.css}: ${value(t, t.modes ? t.modes[mode] : t.value)};`).join('\n') + '\n' + shadowLines(indent);
css += `\n  /* semantic color — light (default) */\n  color-scheme: light;\n${modeBlock('light', '  ')}\n}\n`;
css += `\n/* semantic color — dark: follows the OS unless data-theme="light" is set */\n@media (prefers-color-scheme: dark) {\n  :root:not([data-theme="light"]) {\n    color-scheme: dark;\n${modeBlock('dark', '    ')}\n  }\n}\n`;
css += `\n/* semantic color — dark: explicit opt-in */\n[data-theme="dark"] {\n  color-scheme: dark;\n${modeBlock('dark', '  ')}\n}\n`;
css += `\n[data-theme="light"] {\n  color-scheme: light;\n${modeBlock('light', '  ')}\n}\n`;

// Typography classes from text styles
let typo = '/* Baseline text styles — GENERATED from Figma text styles. */\n';
for (const t of [...flat.values()].filter((t) => t.type === 'typography')) {
  const v = t.value;
  const ref = (x) => (isRef(x) ? `var(${cssName(refId(x))})` : x);
  const cls = '.bl-text-' + t.id.replace(/^type\./, '').replace(/\./g, '-');
  typo += `\n/* ${t.description} */\n${cls} {\n  font-family: ${ref(v.fontFamily)};\n  font-size: ${ref(v.fontSize)};\n  font-weight: ${ref(v.fontWeight)};\n  line-height: ${ref(v.lineHeight)};\n  letter-spacing: ${v.letterSpacing === '0em' ? 'normal' : v.letterSpacing};\n}\n`;
}

// Resolved JSON
const json = {};
for (const t of flat.values()) {
  if (t.type === 'shadow' || t.type === 'typography') continue;
  const entry = { css: t.css, type: t.type, value: resolve(flat, t.value) };
  if (t.modes) for (const m of Object.keys(t.modes)) entry[m] = resolve(flat, t.modes[m], m);
  json[t.id] = entry;
}

const dist = path.join(ROOT, 'dist');
fs.mkdirSync(dist, { recursive: true });
fs.writeFileSync(path.join(dist, 'tokens.css'), css);
fs.writeFileSync(path.join(dist, 'typography.css'), typo);
fs.writeFileSync(path.join(dist, 'tokens.json'), JSON.stringify(json, null, 2) + '\n');

const parts = [css, typo, fs.readFileSync(path.join(ROOT, 'css/base.css'), 'utf8')];
const compDir = path.join(ROOT, 'css/components');
for (const f of fs.readdirSync(compDir).filter((f) => f.endsWith('.css')).sort()) parts.push(fs.readFileSync(path.join(compDir, f), 'utf8'));
fs.writeFileSync(path.join(dist, 'baseline.css'), parts.join('\n'));

const counts = Object.fromEntries(ORDER.map((f) => [f, byFile(f).length]));
console.log(`Built ${flat.size} tokens`, counts, `-> dist/ (tokens.css, typography.css, tokens.json, baseline.css)`);
